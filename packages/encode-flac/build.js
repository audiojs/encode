// src/libflac.wasm.js: libflac.js's minified WASM build of libFLAC, its binary inlined, one ES module with no host I/O.
// The package ships this one file in place of libflacjs, whose 8 MB carry every build (asm.js, dev, maps) and its docs.
//   node build.js   (prepack)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'

const require = createRequire(import.meta.url)
const dist = join(dirname(require.resolve('libflacjs/package.json')), 'dist')
const { version } = require('libflacjs/package.json')
let glue = readFileSync(join(dist, 'libflac.min.wasm.js'), 'utf8')
const wasm = readFileSync(join(dist, 'libflac.min.wasm.wasm')).toString('base64')

// the binary handed in, so nothing is fetched or read from disk (`binary`: the glue declares its own `wasmBinary`)
const patch = (from, to) => {
  if (!glue.includes(from)) throw Error(`libflacjs ${version}: "${from}" not found in libflac.min.wasm.js: see build.js`)
  glue = glue.replace(from, to)
}
patch('null;var Module=Module||{};', 'null;var Module={wasmBinary:binary};')
// the glue wraps window.fetch to load its .wasm by URL; the binary is inlined, so the page's fetch stays its own
patch('if(global&&typeof global.fetch==="function")', 'if(false)')

// the glue, CommonJS, runs as the body of a function given `module` and `__dirname` (in Node it reads its folder at
// load, never using it)
mkdirSync(new URL('./src/', import.meta.url), { recursive: true })
writeFileSync(new URL('./src/libflac.wasm.js', import.meta.url), `// libFLAC (BSD-3-Clause, Xiph.Org) by libflac.js ${version} (MIT, DFKI GmbH): its libflac.min.wasm.js, the binary
// inlined. Generated by build.js; LICENSE.libflac holds both licenses.
const binary = Uint8Array.from(atob('${wasm}'), c => c.charCodeAt(0))
const module = { exports: {} }
;(function (module, __dirname) {
${glue}
}).call(undefined, module, '.')
export default module.exports
`)
